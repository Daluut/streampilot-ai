"use client";

import Link from "next/link";
import { AlertTriangle, Lightbulb, MessageCircleQuestion } from "lucide-react";
import { Badge, Banner, Card, CardHeader, EmptyState } from "./ui";
import { CopyButton } from "./copy-button";
import { formatClock, formatRelative, pluralise } from "@/lib/client/format";
import type { AnalysisResult, ChatMessage, QuestionGroup, SentimentOverview, TopicCluster } from "@/lib/types";

export function SummaryBlock({ analysis, now }: { analysis: AnalysisResult | null; now: number }) {
  if (!analysis) {
    return (
      <EmptyState title="No analysis yet" icon={<Lightbulb aria-hidden className="size-6" />}>
        A summary appears after a few messages arrive. Analysis runs automatically at the interval set in Settings, or you can run it now.
      </EmptyState>
    );
  }
  return (
    <div className="space-y-3 p-4">
      {analysis.aiError ? (
        <Banner tone="warn" title="AI analysis is temporarily unavailable">
          {analysis.aiError} The summary below was produced by local rules instead, and chat is still updating normally.
        </Banner>
      ) : null}
      <p className="text-sm leading-relaxed text-ink/95">{analysis.summary}</p>
      <div className="flex flex-wrap items-center justify-between gap-2 text-xs text-muted">
        <span>
          {analysis.mode === "ai" ? "Generated by " : "Produced by "}
          <span className="text-ink/80">{analysis.engineLabel}</span>
          {" · "}{pluralise(analysis.batchSize, "message")} analysed · {formatRelative(analysis.createdAt, now)}
        </span>
        <CopyButton text={analysis.summary} label="Copy summary" />
      </div>
    </div>
  );
}

export function TopicList({ topics, messages, limit }: { topics: TopicCluster[]; messages: ChatMessage[]; limit?: number }) {
  if (topics.length === 0) {
    return <EmptyState title="No recurring topics yet">Topics appear when the same term shows up in several messages within one analysis window.</EmptyState>;
  }
  const bySeq = new Map(messages.map((m) => [m.seq, m]));
  const max = Math.max(...topics.map((t) => t.messageCount));
  const shown = limit ? topics.slice(0, limit) : topics;
  return (
    <ul className="divide-y divide-line/70">
      {shown.map((topic) => (
        <li key={topic.label} className="space-y-2 px-4 py-3">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <p className="text-sm font-medium text-ink">{topic.label}</p>
            <div className="flex items-center gap-2 text-xs text-muted">
              <span>{topic.messageCount} messages</span>
              <span aria-hidden>·</span>
              <span>last seen {formatClock(topic.latestAt)}</span>
            </div>
          </div>
          <div aria-hidden className="h-1.5 w-full rounded-full bg-raised">
            <div className="h-1.5 rounded-full bg-accent" style={{ width: `${Math.max(6, (topic.messageCount / max) * 100)}%` }} />
          </div>
          <p className="text-xs text-muted">{topic.explanation}</p>
          {topic.sampleSeqs.length > 0 ? (
            <ul className="space-y-1">
              {topic.sampleSeqs.map((seq) => {
                const message = bySeq.get(seq);
                if (!message) return null;
                return (
                  <li key={seq} className="truncate text-xs text-ink/70">
                    <span className="text-muted">{message.username}:</span> {message.text}
                  </li>
                );
              })}
            </ul>
          ) : null}
        </li>
      ))}
    </ul>
  );
}

export function SentimentBar({ sentiment }: { sentiment: SentimentOverview | null }) {
  if (!sentiment || sentiment.total === 0) {
    return <EmptyState title="No reactions measured yet">Reaction counts appear once messages have been analysed.</EmptyState>;
  }
  const pct = (n: number) => (sentiment.total === 0 ? 0 : (n / sentiment.total) * 100);
  const segments = [
    { label: "Positive", count: sentiment.positive, className: "bg-ok" },
    { label: "Neutral or unclear", count: sentiment.neutral, className: "bg-raised" },
    { label: "Negative or frustrated", count: sentiment.negative, className: "bg-bad" },
  ];
  return (
    <div className="space-y-3 p-4">
      <div role="img" aria-label={segments.map((s) => `${s.label}: ${s.count} of ${sentiment.total}`).join(", ")} className="flex h-2.5 w-full overflow-hidden rounded-full bg-raised">
        {segments.map((s) => (
          <div key={s.label} className={`${s.className} h-full`} style={{ width: `${pct(s.count)}%` }} />
        ))}
      </div>
      <ul className="grid grid-cols-1 gap-2 text-xs sm:grid-cols-3">
        {segments.map((s) => (
          <li key={s.label} className="rounded-md border border-line px-3 py-2">
            <p className="text-muted">{s.label}</p>
            <p className="mt-0.5 text-sm text-ink">{s.count} <span className="text-muted">of {sentiment.total} messages</span></p>
          </li>
        ))}
      </ul>
      <p className="text-xs leading-relaxed text-muted">
        Approximate reading of chat wording using a small keyword list. It does not measure how viewers feel, sarcasm is often missed, and messages with mixed signals are counted as neutral ({sentiment.ambiguous} this window).
      </p>
    </div>
  );
}

export function SuggestionList({ analysis, limit }: { analysis: AnalysisResult | null; limit?: number }) {
  if (!analysis || analysis.suggestions.length === 0) {
    return (
      <EmptyState title="No recommended actions right now">
        Suggestions appear when a question repeats, technical problems are reported, or chat asks for something specific. StreamPilot never posts these for you.
      </EmptyState>
    );
  }
  const shown = limit ? analysis.suggestions.slice(0, limit) : analysis.suggestions;
  return (
    <ul className="divide-y divide-line/70">
      {shown.map((s) => (
        <li key={s.id} className="flex flex-col gap-2 px-4 py-3 sm:flex-row sm:items-start sm:justify-between">
          <div className="min-w-0">
            <p className="text-sm text-ink/95">{s.text}</p>
            <p className="mt-1 text-xs text-muted">Why: {s.basis}</p>
          </div>
          <CopyButton text={s.text} label="Copy" className="shrink-0" />
        </li>
      ))}
    </ul>
  );
}

export function QuestionMini({ groups }: { groups: Omit<QuestionGroup, "tokens">[] }) {
  const repeated = groups.filter((g) => g.count >= 2 && g.status === "open").slice(0, 3);
  if (repeated.length === 0) {
    return (
      <EmptyState title="No repeated open questions" icon={<MessageCircleQuestion aria-hidden className="size-6" />}>
        Questions asked by more than one viewer, with similar wording, will be grouped here.
      </EmptyState>
    );
  }
  return (
    <ul className="divide-y divide-line/70">
      {repeated.map((g) => (
        <li key={g.id} className="flex items-start justify-between gap-3 px-4 py-3">
          <div className="min-w-0">
            <p className="text-sm text-ink">{g.canonical}</p>
            <p className="mt-1 text-xs text-muted">
              Asked {g.count} times · {g.responseDetected ? "a reply is visible in chat" : "No response detected in the available chat window."}
            </p>
          </div>
          <Badge tone="accent">{g.count}×</Badge>
        </li>
      ))}
      <li className="px-4 py-2.5 text-xs">
        <Link href="/questions" className="text-accent-strong hover:underline focus-visible:outline-2 focus-visible:outline-accent-strong">Open the question queue</Link>
      </li>
    </ul>
  );
}

export function AnalysisHistory({ analyses, now }: { analyses: AnalysisResult[]; now: number }) {
  if (analyses.length === 0) {
    return <EmptyState title="No analysis runs yet">Each run is listed here with its engine, batch size and time.</EmptyState>;
  }
  return (
    <div className="overflow-x-auto">
      <table className="w-full min-w-[560px] text-left text-xs">
        <thead className="text-muted">
          <tr className="border-b border-line">
            <th scope="col" className="px-4 py-2 font-medium">When</th>
            <th scope="col" className="px-4 py-2 font-medium">Engine</th>
            <th scope="col" className="px-4 py-2 font-medium">Messages</th>
            <th scope="col" className="px-4 py-2 font-medium">Summary</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-line/70">
          {analyses.map((a) => (
            <tr key={a.id} className="align-top">
              <td className="px-4 py-2 whitespace-nowrap text-muted">{formatRelative(a.createdAt, now)}</td>
              <td className="px-4 py-2 whitespace-nowrap">
                <span className="text-ink/80">{a.engineLabel}</span>
                {a.aiError ? <span className="ml-1 inline-flex items-center gap-1 text-amber-300"><AlertTriangle aria-hidden className="size-3" />fallback</span> : null}
              </td>
              <td className="px-4 py-2 whitespace-nowrap text-muted">{a.batchSize}</td>
              <td className="px-4 py-2 text-ink/80">{a.summary.length > 140 ? `${a.summary.slice(0, 137)}…` : a.summary}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

